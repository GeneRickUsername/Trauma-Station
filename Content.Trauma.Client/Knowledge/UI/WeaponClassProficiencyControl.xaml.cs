using System;
using Content.Trauma.Common.Knowledge;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Trauma.Client.Knowledge.UI;

public enum SpecializationCategory
{
    Speed,
    Attack,
    Defense,
    Damage
}

[GenerateTypedNameReferences]
public sealed partial class WeaponClassProficiencyControl : BoxContainer
{
    public event Action<int>? OnChangeProficiencyLevel;
    public event Action<SpecializationCategory, int>? OnChangeSpecializationAllocation;

    public int Level { get; private set; }
    public SpecializationAllocation Allocation { get; private set; }

    private readonly int _costPerLevel;

    public WeaponClassProficiencyControl(string name, int costPerLevel)
    {
        RobustXamlLoader.Load(this);

        _costPerLevel = costPerLevel;
        WeaponClassLabel.Text = name;

        DecreaseButton.OnPressed += _ => OnChangeProficiencyLevel?.Invoke(-1);
        IncreaseButton.OnPressed += _ => OnChangeProficiencyLevel?.Invoke(+1);

        // Bind 4-category specialization adjusters
        SpeedDecreaseButton.OnPressed += _ => OnChangeSpecializationAllocation?.Invoke(SpecializationCategory.Speed, -1);
        SpeedIncreaseButton.OnPressed += _ => OnChangeSpecializationAllocation?.Invoke(SpecializationCategory.Speed, +1);

        AttackDecreaseButton.OnPressed += _ => OnChangeSpecializationAllocation?.Invoke(SpecializationCategory.Attack, -1);
        AttackIncreaseButton.OnPressed += _ => OnChangeSpecializationAllocation?.Invoke(SpecializationCategory.Attack, +1);

        DefenseDecreaseButton.OnPressed += _ => OnChangeSpecializationAllocation?.Invoke(SpecializationCategory.Defense, -1);
        DefenseIncreaseButton.OnPressed += _ => OnChangeSpecializationAllocation?.Invoke(SpecializationCategory.Defense, +1);

        DamageDecreaseButton.OnPressed += _ => OnChangeSpecializationAllocation?.Invoke(SpecializationCategory.Damage, -1);
        DamageIncreaseButton.OnPressed += _ => OnChangeSpecializationAllocation?.Invoke(SpecializationCategory.Damage, +1);
    }

    public void SetLevel(int level, int racialBase = 0)
    {
        Level = level;
        var added = Math.Max(Level - racialBase, 0);
        var cost = added * _costPerLevel;

        LevelLabel.Text = $"Proficiency Lvl: {Level} (Cost: {cost})";
        DecreaseButton.Disabled = Level <= racialBase;
        IncreaseButton.Disabled = false;

        var isProficient = Level > 0;
        var color = !isProficient ? Color.Gray : Color.White;
        LevelLabel.Modulate = color;
        WeaponClassLabel.Modulate = color;

        SpecializationsContainer.Visible = isProficient;
        UpdateSpecializationUI();
    }

    public void SetSpecializationAllocation(SpecializationAllocation alloc)
    {
        Allocation = alloc;
        UpdateSpecializationUI();
    }

    private void UpdateSpecializationUI()
    {
        var isProficient = Level > 0;

        var speedCost = CalculateCategoryCost(Allocation.Speed);
        var attackCost = CalculateCategoryCost(Allocation.Attack);
        var defenseCost = CalculateCategoryCost(Allocation.Defense);
        var damageCost = CalculateCategoryCost(Allocation.Damage);

        SpeedLabel.Text = $"+{Allocation.Speed} (Cost: {speedCost})";
        AttackLabel.Text = $"+{Allocation.Attack} (Cost: {attackCost})";
        DefenseLabel.Text = $"+{Allocation.Defense} (Cost: {defenseCost})";
        DamageLabel.Text = $"+{Allocation.Damage} (Cost: {damageCost})";

        SpeedDecreaseButton.Disabled = !isProficient || Allocation.Speed <= 0;
        SpeedIncreaseButton.Disabled = !isProficient;

        AttackDecreaseButton.Disabled = !isProficient || Allocation.Attack <= 0;
        AttackIncreaseButton.Disabled = !isProficient;

        DefenseDecreaseButton.Disabled = !isProficient || Allocation.Defense <= 0;
        DefenseIncreaseButton.Disabled = !isProficient;

        DamageDecreaseButton.Disabled = !isProficient || Allocation.Damage <= 0;
        DamageIncreaseButton.Disabled = !isProficient;
    }

    private int CalculateCategoryCost(int points)
    {
        if (points <= 0)
            return 0;

        return _costPerLevel * (points * (points + 1) / 2);
    }
}
